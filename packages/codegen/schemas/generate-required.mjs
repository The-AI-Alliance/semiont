#!/usr/bin/env node
// Generate what each component schema requires of a value, as the Rust and
// Kotlin SDKs read it as they build, one copy in each:
//
//   packages/rust/sdk/src/required-schemas.json            (read by packages/rust/sdk/build.rs)
//   packages/kotlin/sdk/src/codegen/required-schemas.json  (read by the SDK's generator)
//
// The reading of the schemas, and the rules a shape states, are
// required-shapes.mjs's, shared with every SDK's generator. Neither build
// runs them, so the copies are committed; `--check` compares without
// writing (the CI drift gate).

import { dirname, resolve } from 'node:path';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { readRequiredShapes } from './required-shapes.mjs';
import { writeOrCheck } from '../lib/committed-source.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const OUTS = ['packages/rust/sdk/src/required-schemas.json', 'packages/kotlin/sdk/src/codegen/required-schemas.json'];
const CHECK = process.argv.includes('--check');

const { names, shapes, inline } = readRequiredShapes(ROOT, (message) => {
  console.error(`✗ ${message}`);
  process.exit(1);
});

const text = `{
  "$comment": "GENERATED from the component schemas of protocol/specs/src/openapi.json by packages/codegen/schemas/generate-required.mjs — do not edit. What each requires of a value, by its name: the rules are packages/codegen/schemas/required-shapes.mjs's.",
  "schemas": {
${names.map((name) => `    ${JSON.stringify(name)}: ${JSON.stringify(shapes.get(name))}`).join(',\n')}
  }
}
`;

for (const out of OUTS) writeOrCheck(ROOT, resolve(ROOT, out), text, CHECK);

// Aeson's object map does not preserve JSON member order. Spell ordered
// members as pairs, retaining the shared generator's first-fault order.
function ordered(shape) {
  const result = { ...shape };
  if (shape.members !== undefined) result.members = Object.entries(shape.members).map(([name, member]) => [name, ordered(member)]);
  for (const key of ['items', 'values']) if (shape[key] !== undefined) result[key] = ordered(shape[key]);
  for (const key of ['oneOf', 'allOf']) if (shape[key] !== undefined) result[key] = shape[key].map(ordered);
  return result;
}
const registry = JSON.parse(readFileSync(resolve(ROOT, 'protocol/specs/src/bus/registry.json'), 'utf8'));
const channels = {};
for (const row of registry.channels) {
  let shape;
  switch (row.shape) {
    case 'schema': shape = { ref: row.schema }; break;
    case 'storedEvent': shape = { ref: row.enriched ? 'EnrichedResourceEvent' : 'StoredEventResponse' }; break;
    case 'envelope': shape = { kinds: ['object'], required: ['response'], members: { response: { ref: row.schema } }, closed: ['response'] }; break;
    case 'empty': case 'void': shape = { kinds: ['object'], closed: [] }; break;
    default: throw new Error(`unsupported required Haskell channel shape: ${row.shape}`);
  }
  if (shape.ref !== undefined && !shapes.has(shape.ref)) throw new Error(`unknown required channel schema: ${shape.ref}`);
  channels[row.channel] = ordered(shape);
}
const openapiFile = resolve(ROOT, 'protocol/specs/src/openapi.json');
const openapi = JSON.parse(readFileSync(openapiFile, 'utf8'));
const http = {};
for (const item of Object.values(openapi.paths)) {
  const file = item.$ref === undefined ? openapiFile : resolve(dirname(openapiFile), item.$ref);
  const path = item.$ref === undefined ? item : JSON.parse(readFileSync(file, 'utf8'));
  for (const operation of Object.values(path).filter((value) => value?.operationId !== undefined)) {
    const success = Object.entries(operation.responses).filter(([status]) => /^2/.test(status));
    if (success.length !== 1) throw new Error(`ambiguous required HTTP success: ${operation.operationId}`);
    const content = Object.values(success[0][1].content);
    if (content.length !== 1 || content[0].schema === undefined) throw new Error(`ambiguous required HTTP content: ${operation.operationId}`);
    const name = operation.operationId[0].toUpperCase() + operation.operationId.slice(1);
    http[name] = ordered(inline(content[0].schema, file));
  }
}
const haskellJSON = JSON.stringify({ schemas: Object.fromEntries(names.map((name) => [name, ordered(shapes.get(name))])), channels, http });
const haskellLiteral = '"' + Array.from(haskellJSON).map((character) => {
  const point = character.codePointAt(0);
  if (character === '"' || character === '\\') return '\\' + character;
  return point >= 32 && point <= 126 ? character : '\\x' + point.toString(16) + '\\&';
}).join('') + '"';
const haskellSource = `-- Generated by packages/codegen/schemas/generate-required.mjs. Do not edit.
{-# LANGUAGE OverloadedStrings #-}
module Semiont.Internal.Generated.Required (shapesJSON) where
import Data.Text (Text)
shapesJSON :: Text
shapesJSON = ${haskellLiteral}
`;
writeOrCheck(ROOT, resolve(ROOT, 'packages/haskell/sdk/generated/Semiont/Internal/Generated/Required.hs'), haskellSource, CHECK);
