/**
 * How the Weaver suite reads the graph: what a stored row is read as, an
 * annotation or a resource, and what the graph is meant to hold of an
 * annotation the record holds.
 *
 * This suite reads the graph with a reader of its own, held to the same case
 * table the Weaver's codec is held to (specs/src/graph/codec-cases.json, run
 * by graph-codec.test.ts), so that it judges a Weaver by something other than
 * the Weaver's own code. The other way would be for `semiont_graph` to offer
 * a small command that prints a resource's rows, decoded, as JSON, which the
 * harness would call: one codec in the repository and no copy here, at the
 * cost that the suite would then read a Weaver through the Weaver's codec.
 *
 * A reader manufactures nothing. A row without a field it must have is
 * refused by the field's name, and a field a row does not hold is left out of
 * what is read.
 */
import { annotationId, getBodySource, getEntityTypes, getTargetSelector, getTargetSource, resourceId } from '@semiont/core';
import type { Annotation, components, ResourceDescriptor } from '@semiont/core';
import { formatErrors, validators } from '@semiont/core/openapi';

/** A node's properties, as a store answers them. Nothing in one is trusted until it is read. */
export type Row = Readonly<Record<string, unknown>>;

export const isRow = (value: unknown): value is Row => typeof value === 'object' && value !== null && !Array.isArray(value);

export const isStrings = (value: unknown): value is string[] => Array.isArray(value) && value.every((one) => typeof one === 'string');

type Agent = NonNullable<Annotation['creator']>;
type Selector = NonNullable<Exclude<Annotation['target'], string>['selector']>;

/** What the graph holds of an annotation, each part as the value it is. */
interface Held {
  id: string;
  resourceId: string;
  motivation: Annotation['motivation'];
  creator: Agent;
  created: string;
  selector: Selector | undefined;
  /** The resource the annotation links to. */
  source: string | undefined;
  modified: string | undefined;
  generator: Annotation['generator'];
}

/**
 * The annotation those parts and its entity tags are. Tags are edges, and a
 * store answers edges in no promised order, so they are held in one: sorted,
 * and then the link. A tag with no name is no tag.
 */
function annotationOf(held: Held, tags: readonly string[]): Annotation {
  const body: components['schemas']['AnnotationBody'][] = [];
  for (const tag of [...tags].sort()) {
    if (tag) body.push({ type: 'TextualBody', value: tag, purpose: 'tagging' });
  }
  if (held.source) body.push({ type: 'SpecificResource', source: resourceId(held.source), purpose: 'linking' });

  const source = resourceId(held.resourceId);
  const annotation: Annotation = {
    '@context': 'http://www.w3.org/ns/anno.jsonld',
    type: 'Annotation',
    id: annotationId(held.id),
    motivation: held.motivation,
    target: held.selector ? { source, selector: held.selector } : { source },
    creator: held.creator,
    created: held.created,
  };
  if (body.length > 0) annotation.body = body;
  if (held.modified) annotation.modified = held.modified;
  if (held.generator) annotation.generator = held.generator;
  return annotation;
}

/**
 * A property of an annotation's row, as text. A date may be held as the
 * database's own kind of date, which the driver answers as an object: its
 * text is what is read.
 */
function text(row: Row, key: string): string | undefined {
  const value = row[key];
  if (value === undefined || value === null) return undefined;
  return typeof value === 'string' ? value : String(value);
}

/** One agent, or several: who an annotation is generated by, and who a resource is by. */
const isAgents = (value: unknown): value is Agent | Agent[] => (Array.isArray(value) ? value.every((one) => validators.Agent(one)) : validators.Agent(value));

/**
 * A property a row holds as JSON, parsed and held to what the spec says it
 * is. `of` names the row and `key` the property, for the refusal.
 */
function held<T>(of: string, key: string, stored: string, is: (value: unknown) => value is T): T {
  let value: unknown;
  try {
    value = JSON.parse(stored);
  } catch {
    throw new Error(`${of}: the stored ${key} is not JSON: ${stored}`);
  }
  if (!is(value)) throw new Error(`${of}: the stored ${key} is not what the codec writes: ${stored}`);
  return value;
}

/**
 * An annotation's row and the names its tag edges go to, read as the
 * annotation. The creator, the selector and the generator are held as JSON.
 * What is read is held to the spec's Annotation before it is answered.
 */
export function readAnnotation(row: Row, tags: readonly string[]): Annotation {
  const id = text(row, 'id');
  if (!id) throw new Error('Annotation missing required field: id');
  const required = (key: string): string => {
    const value = text(row, key);
    if (!value) throw new Error(`Annotation ${id} missing required field: ${key}`);
    return value;
  };
  const of = `Annotation ${id}`;
  const motivation = required('motivation');
  if (!validators.Motivation(motivation)) throw new Error(`${of}: the stored motivation is not one the spec names: ${motivation}`);
  const selector = text(row, 'selector');
  const generator = text(row, 'generator');
  const annotation = annotationOf(
    {
      id,
      resourceId: required('resourceId'),
      motivation,
      creator: held(of, 'creator', required('creator'), validators.Agent),
      created: required('created'),
      selector: selector ? held(of, 'selector', selector, validators.AnnotationSelector) : undefined,
      source: text(row, 'source'),
      modified: text(row, 'modified'),
      generator: generator ? held(of, 'generator', generator, isAgents) : undefined,
    },
    tags,
  );
  if (!validators.Annotation(annotation)) throw new Error(`${of}: the row is not an annotation the spec allows: ${formatErrors(validators.Annotation.errors)}`);
  return annotation;
}

/**
 * An agent as the graph holds it: who, and not what a person is called. A
 * person's name is the directory's, joined onto a read and changed there, so
 * the graph holds none. Software is held as the record gives it.
 */
function who(agent: Agent): Agent {
  if (agent['@type'] !== 'Person') return agent;
  const { name: _theDirectorys, ...rest } = agent;
  return rest;
}

/**
 * What the graph is meant to hold of an annotation the record holds. The
 * graph keeps what its queries need and no more, so a case holds the graph to
 * this and never to the record's annotation itself.
 */
export function intendedGraphAnnotation(annotation: Annotation): Annotation {
  if (annotation.creator === undefined) throw new Error(`Annotation ${annotation.id} missing required field: creator`);
  const generator = annotation.generator;
  return annotationOf(
    {
      id: annotation.id,
      resourceId: getTargetSource(annotation.target),
      motivation: annotation.motivation,
      creator: who(annotation.creator),
      created: annotation.created,
      selector: getTargetSelector(annotation.target),
      source: getBodySource(annotation.body) ?? undefined,
      modified: annotation.modified,
      generator: generator === undefined ? undefined : Array.isArray(generator) ? generator.map(who) : who(generator),
    },
    getEntityTypes(annotation),
  );
}

/**
 * A resource's row, read as the resource, with its one representation
 * rebuilt. Who it is by is held as JSON. `false` and an empty list are values
 * a row holds; only a field that is not there, or is the empty text, is
 * missing. What is read is held to the spec's ResourceDescriptor before it is
 * answered.
 */
export function readResource(row: Row): ResourceDescriptor {
  const id = row['id'];
  if (typeof id !== 'string' || id === '') throw new Error('Resource missing required field: id');
  const missing = (key: string) => new Error(`Resource ${id} missing required field: ${key}`);
  const required = (key: string): string => {
    const value = row[key];
    if (typeof value !== 'string' || value === '') throw missing(key);
    return value;
  };
  const name = required('name');
  const entityTypes = row['entityTypes'];
  if (!isStrings(entityTypes)) throw missing('entityTypes');
  const mediaType = required('format');
  const archived = row['archived'];
  if (typeof archived !== 'boolean') throw missing('archived');
  const dateCreated = required('created');
  const creator = required('creator');
  const checksum = required('contentChecksum');
  const storageUri = row['storageUri'];
  const resource: ResourceDescriptor = {
    '@context': 'https://schema.org/',
    '@id': resourceId(id),
    name,
    entityTypes,
    representations: [{ mediaType, checksum, rel: 'original', ...(typeof storageUri === 'string' && storageUri !== '' ? { storageUri } : {}) }],
    archived,
    dateCreated,
    wasAttributedTo: held(`Resource ${id}`, 'creator', creator, isAgents),
  };
  if (!validators.ResourceDescriptor(resource)) throw new Error(`Resource ${id}: the row is not a resource the spec allows: ${formatErrors(validators.ResourceDescriptor.errors)}`);
  return resource;
}
