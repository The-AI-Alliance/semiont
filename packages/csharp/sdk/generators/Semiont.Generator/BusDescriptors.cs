using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace Semiont.Generator;

internal static class BusDescriptors
{
    internal static string Emit(string source, Dictionary<string, JsonElement> definitions)
    {
        using var registry = JsonDocument.Parse(source);
        var root = registry.RootElement;
        var scopes = new HashSet<string>(root.GetProperty("audience").GetProperty("scoped").EnumerateArray()
            .Select(value => value.GetString() ?? throw new InvalidOperationException("Missing scoped channel")), StringComparer.Ordinal);
        var types = new Dictionary<string, string>(StringComparer.Ordinal);
        var envelopes = new HashSet<string>(StringComparer.Ordinal);
        definitions.Add("EmptyBusPayload", JsonSerializer.Deserialize<JsonElement>("""{"type":"object","maxProperties":0}"""));
        var code = new StringBuilder("// <auto-generated/>\nusing Semiont.Types;\nnamespace Semiont;\npublic static class BusChannels {\n");
        foreach (var row in root.GetProperty("channels").EnumerateArray())
        {
            var channel = Required(row, "channel");
            var name = Member(channel);
            string type;
            switch (Required(row, "shape"))
            {
                case "schema": type = Required(row, "schema"); break;
                case "storedEvent":
                    type = row.TryGetProperty("enriched", out var enriched) && enriched.GetBoolean()
                        ? "EnrichedResourceEvent" : "StoredEventResponse";
                    break;
                case "envelope":
                    var schema = Required(row, "schema");
                    type = schema + "BusEnvelope";
                    if (envelopes.Add(schema))
                    {
                        definitions.Add(type, JsonSerializer.SerializeToElement(new
                        {
                            type = "object",
                            properties = new Dictionary<string, object>
                            {
                                ["response"] = new Dictionary<string, string> { ["$ref"] = schema + ".json" },
                            },
                            required = new[] { "response" },
                            additionalProperties = false,
                        }));
                    }
                    break;
                case "empty":
                case "void": type = "EmptyBusPayload"; break;
                default: throw new InvalidOperationException("Unknown bus payload shape for " + channel);
            }
            if (!definitions.ContainsKey(type)) throw new InvalidOperationException("Missing bus payload schema " + type);
            types.Add(channel, type);
            code.Append("public static BusChannel<").Append(type).Append("> ").Append(name)
                .Append(" { get; } = new(").Append(JsonSerializer.Serialize(channel)).Append(", ")
                .Append(scopes.Contains(channel) ? "true" : "false").Append(");\n");
        }
        code.Append("}\npublic static class BusOperations {\n");
        foreach (var row in root.GetProperty("operations").EnumerateArray())
        {
            var request = Required(row, "request");
            var result = Required(row, "result");
            var failure = Required(row, "failure");
            code.Append("public static BusOperation<").Append(types[request]).Append(", ")
                .Append(types[result]).Append(", ").Append(types[failure]).Append("> ").Append(Member(request))
                .Append(" { get; } = new(BusChannels.").Append(Member(request)).Append(", BusChannels.")
                .Append(Member(result)).Append(", BusChannels.").Append(Member(failure)).Append(");\n");
        }
        return code.Append("}\n").ToString();
    }

    private static string Required(JsonElement row, string name) =>
        row.GetProperty(name).GetString() ?? throw new InvalidOperationException("Missing bus registry member " + name);

    private static string Member(string channel) => string.Concat(channel.Split(':', '-')
        .Select(part => char.ToUpperInvariant(part[0]) + part.Substring(1)));
}
