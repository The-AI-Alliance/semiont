using System;
using System.Text.Json;

namespace Semiont.Generator;

internal static class Identifiers
{
    internal static string Emit(string name, string pattern)
    {
        if (pattern.Length < 2 || pattern[0] != '^' || pattern[pattern.Length - 1] != '$')
        {
            throw new InvalidOperationException(name + " has an unanchored identifier pattern.");
        }
        // .NET includes NEL in whitespace and excludes BOM; ECMAScript does the reverse.
        var body = pattern.Substring(1, pattern.Length - 2).Replace("\\S", "(?:\\S|\\u0085)");
        var check = "global::System.Text.RegularExpressions.Regex.IsMatch(text, " +
            JsonSerializer.Serialize("\\A" + body + "\\z") + ", global::System.Text.RegularExpressions.RegexOptions.CultureInvariant)";
        if (pattern.Contains("\\S"))
        {
            check += " && text.IndexOf('\\uFEFF') < 0";
        }
        return $$"""
            // <auto-generated/>
            #nullable enable
            namespace Semiont.Identifiers;

            [global::System.Text.Json.Serialization.JsonConverter(typeof({{name}}JsonConverter))]
            public readonly record struct {{name}}
            {
                private readonly string? value;

                private {{name}}(string value) => this.value = value;

                public string Value => value ?? throw new global::System.InvalidOperationException("An uninitialized {{name}} has no value.");

                public static {{name}} Parse(string text) => TryParse(text, out var parsed)
                    ? parsed
                    : throw new global::System.FormatException("The value is not a {{name}}.");

                public static bool TryParse(string? text, out {{name}} parsed)
                {
                    if (text is not null && {{check}})
                    {
                        parsed = new {{name}}(text);
                        return true;
                    }
                    parsed = default;
                    return false;
                }

                public override string ToString() => Value;
            }

            internal sealed class {{name}}JsonConverter : global::System.Text.Json.Serialization.JsonConverter<{{name}}>
            {
                public override {{name}} Read(ref global::System.Text.Json.Utf8JsonReader reader, global::System.Type type, global::System.Text.Json.JsonSerializerOptions options)
                {
                    if (reader.TokenType == global::System.Text.Json.JsonTokenType.String && {{name}}.TryParse(reader.GetString(), out var parsed))
                    {
                        return parsed;
                    }
                    throw new global::System.Text.Json.JsonException("The value is not a {{name}}.");
                }

                public override void Write(global::System.Text.Json.Utf8JsonWriter writer, {{name}} value, global::System.Text.Json.JsonSerializerOptions options)
                {
                    try
                    {
                        writer.WriteStringValue(value.Value);
                    }
                    catch (global::System.InvalidOperationException error)
                    {
                        throw new global::System.Text.Json.JsonException(error.Message, error);
                    }
                }
            }
            """;
    }
}
