using System;
using System.Collections.Generic;
using System.Text.Json;

namespace Semiont.Generator;

internal static class UnicodeCase
{
    /// <summary>Whether a code point is cased, and whether it is case-ignorable, as the table
    /// packages/codegen/schemas/generate-unicode-case.mjs writes from Unicode's Cased and Case_Ignorable
    /// properties: .NET gives neither.</summary>
    internal static string Emit(string table)
    {
        using var document = JsonDocument.Parse(table);
        var cased = Ranges(document.RootElement, "cased");
        var ignorable = Ranges(document.RootElement, "caseIgnorable");
        return $$"""
            // <auto-generated/>
            namespace Semiont.Annotations;

            internal static class UnicodeCase
            {
                internal static bool Cased(int point) => Within(point, CasedFirsts, CasedLasts);

                internal static bool CaseIgnorable(int point) => Within(point, CaseIgnorableFirsts, CaseIgnorableLasts);

                private static bool Within(int point, global::System.ReadOnlySpan<int> firsts, global::System.ReadOnlySpan<int> lasts)
                {
                    var at = global::System.MemoryExtensions.BinarySearch(lasts, point);
                    if (at >= 0)
                    {
                        return true;
                    }
                    at = ~at;
                    return at < firsts.Length && firsts[at] <= point;
                }

                private static global::System.ReadOnlySpan<int> CasedFirsts => [{{cased.Firsts}}];

                private static global::System.ReadOnlySpan<int> CasedLasts => [{{cased.Lasts}}];

                private static global::System.ReadOnlySpan<int> CaseIgnorableFirsts => [{{ignorable.Firsts}}];

                private static global::System.ReadOnlySpan<int> CaseIgnorableLasts => [{{ignorable.Lasts}}];
            }
            """;
    }

    private static (string Firsts, string Lasts) Ranges(JsonElement table, string property)
    {
        if (!table.TryGetProperty(property, out var ranges) || ranges.ValueKind != JsonValueKind.Array || ranges.GetArrayLength() == 0)
        {
            throw new InvalidOperationException("unicode-case.json gives no ranges of " + property + ".");
        }
        var firsts = new List<int>();
        var lasts = new List<int>();
        foreach (var range in ranges.EnumerateArray())
        {
            if (range.ValueKind != JsonValueKind.Array || range.GetArrayLength() != 2)
            {
                throw new InvalidOperationException("A range of " + property + " in unicode-case.json is not a first and a last code point.");
            }
            var first = range[0].GetInt32();
            var last = range[1].GetInt32();
            if (last < first || (lasts.Count > 0 && first <= lasts[lasts.Count - 1]))
            {
                throw new InvalidOperationException("The ranges of " + property + " in unicode-case.json do not ascend.");
            }
            firsts.Add(first);
            lasts.Add(last);
        }
        return (string.Join(", ", firsts), string.Join(", ", lasts));
    }
}
