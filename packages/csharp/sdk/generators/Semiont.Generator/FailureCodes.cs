using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace Semiont.Generator;

internal static class FailureCodes
{
    /// <summary>The code a bus request fails under, by the code its failure states: one case for each code CommandError
    /// names, as protocol/specs/src/errors/codes.json maps it (`busRequest`, by `wire`), and the unrecognized failure
    /// for a failure that states none. A code either side names that the other does not fails generation.</summary>
    internal static string Emit(string errors, JsonElement commandError, string codeType)
    {
        var named = commandError.GetProperty("properties").GetProperty("code").GetProperty("enum").EnumerateArray()
            .Select(code => code.GetString() ?? throw new InvalidOperationException("A code of CommandError is null.")).ToArray();
        using var document = JsonDocument.Parse(errors);
        var family = document.RootElement.GetProperty("busRequest");
        var mapped = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var row in family.GetProperty("codes").EnumerateArray())
        {
            if (!row.TryGetProperty("wire", out var wire)) continue;
            var code = wire.GetString() ?? throw new InvalidOperationException("A bus request's failure maps a null code.");
            if (!named.Contains(code, StringComparer.Ordinal))
                throw new InvalidOperationException("errors/codes.json maps " + code + ", which is no code of CommandError.");
            mapped.Add(code, row.GetProperty("code").GetString() ?? throw new InvalidOperationException("A bus request's failure is null."));
        }
        var unrecognized = family.GetProperty("unrecognizedFailure").GetString()
            ?? throw new InvalidOperationException("errors/codes.json names no unrecognized failure.");
        var type = "global::Semiont.Types." + codeType;
        var text = new StringBuilder("// <auto-generated/>\nnamespace Semiont.Protocol;\n\ninternal static class FailureCodes\n{\n");
        text.Append("    internal static string Of(").Append(type).Append("? code) => code switch\n    {\n");
        foreach (var code in named)
        {
            if (!mapped.TryGetValue(code, out var failure))
                throw new InvalidOperationException("errors/codes.json maps CommandError's code " + code + " to no bus request's failure.");
            text.Append("        ").Append(type).Append('.').Append(Models.Pascal(code)).Append(" => ").Append(JsonSerializer.Serialize(failure)).Append(",\n");
        }
        text.Append("        null => ").Append(JsonSerializer.Serialize(unrecognized)).Append(",\n");
        text.Append("        _ => throw new global::System.ArgumentOutOfRangeException(nameof(code), code, \"No code of CommandError.\"),\n    };\n}\n");
        return text.ToString();
    }
}
